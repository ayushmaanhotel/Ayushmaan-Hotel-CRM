/**
 * Builds src/lib/vfs-fonts.ts from TTF files placed in ./fonts/
 *
 *   mkdir -p fonts && cd fonts
 *   # download SIL-OFL licensed fonts (free for commercial use):
 *   #   Inter (Regular, SemiBold, Italic, SemiBoldItalic)          https://rsms.me/inter/
 *   #   Playfair Display (Regular, SemiBold, Italic, SemiBoldItalic) https://fonts.google.com/specimen/Playfair+Display
 *   #   Noto Sans Devanagari (Regular, SemiBold)                   https://fonts.google.com/noto/specimen/Noto+Sans+Devanagari
 *   node scripts/build-fonts.mjs
 *
 * Keeps the PWA bundle honest: only the weights actually used are embedded
 * (~6 files ≈ 1.1 MB of base64, cached once by the service worker).
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../fonts', import.meta.url).pathname;
const out = {};

for (const f of readdirSync(dir)) {
  if (!f.endsWith('.ttf')) continue;
  out[f] = readFileSync(join(dir, f)).toString('base64');
  console.log('embedded', f, (out[f].length / 1024).toFixed(0) + ' KB b64');
}

writeFileSync(
  new URL('../src/lib/vfs-fonts.ts', import.meta.url).pathname,
  '/* GENERATED by scripts/build-fonts.mjs — do not edit */\n' +
  `export const vfs: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`
);
console.log('wrote src/lib/vfs-fonts.ts');
